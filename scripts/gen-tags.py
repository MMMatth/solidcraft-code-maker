#!/usr/bin/env python3
"""Writes code-maker-src/src/tags.rs from the official ArUco and AprilTag dictionaries.

Usage: scripts/gen-tags.py <dir>

<dir> holds the files downloaded from
  https://github.com/opencv/opencv  modules/objdetect/src/aruco/predefined_dictionaries.hpp   (Apache-2.0)
  https://github.com/AprilRobotics/apriltag  tag16h5.c tag25h9.c tag36h11.c tagStandard41h12.c  (BSD-2-Clause)

Only the first rotation of every ArUco marker is kept (the others are turns of it).
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = []


def emit(line=""):
    out.append(line)


def groups(text):
    """Every innermost `{ n, n, ... }` of a C array, as lists of ints."""
    return [[int(v) for v in g.split(",") if v.strip()] for g in re.findall(r"\{([^{}]*)\}", text)]


def array_body(text, name):
    start = text.index(name)
    start = text.index("=", start)
    depth, i = 0, text.index("{", start)
    first = i
    while True:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[first : i + 1]
        i += 1


emit("// Generated by scripts/gen-tags.py: do not edit.")
emit("//")
emit("// ArUco dictionaries: from OpenCV (Apache-2.0, https://github.com/opencv/opencv).")
emit("// AprilTag families: from AprilRobotics/apriltag (BSD-2-Clause, https://github.com/AprilRobotics/apriltag).")
emit()
emit("/// An ArUco dictionary: `count` markers of `size` x `size` bits. Each marker is `size * size` bits,")
emit("/// row by row, most significant bit first, 1 for white; the last byte holds the leftover bits on its right.")
emit("pub struct Aruco {")
emit("    pub name: &'static str,")
emit("    pub size: usize,")
emit("    pub count: usize,")
emit("    pub bytes: &'static [u8],")
emit("}")
emit()

hpp = (src / "predefined_dictionaries.hpp").read_text()
# (array name, marker size, dictionaries cut from it: (name, count))
sources = [
    ("DICT_4X4_1000_BYTES", 4, [("4x4_50", 50), ("4x4_100", 100), ("4x4_250", 250), ("4x4_1000", 1000)]),
    ("DICT_5X5_1000_BYTES", 5, [("5x5_50", 50), ("5x5_100", 100), ("5x5_250", 250), ("5x5_1000", 1000)]),
    ("DICT_6X6_1000_BYTES", 6, [("6x6_50", 50), ("6x6_100", 100), ("6x6_250", 250), ("6x6_1000", 1000)]),
    ("DICT_7X7_1000_BYTES", 7, [("7x7_50", 50), ("7x7_100", 100), ("7x7_250", 250), ("7x7_1000", 1000)]),
    ("DICT_ARUCO_BYTES", 5, [("original", 1024)]),
    ("DICT_ARUCO_MIP_36h12_BYTES", 6, [("mip_36h12", 250)]),
]
entries = []
for array, size, dicts in sources:
    gs = groups(array_body(hpp, array))
    nbytes = (size * size + 7) // 8
    assert all(len(g) == nbytes for g in gs), array
    assert len(gs) % 4 == 0, array
    markers = gs[0::4]  # rotation 0 of each marker
    biggest = max(c for _, c in dicts)
    assert len(markers) >= biggest, (array, len(markers))
    ident = array.removesuffix("_BYTES").upper()
    flat = [b for m in markers[:biggest] for b in m]
    emit(f"static {ident}: [u8; {len(flat)}] = [")
    for i in range(0, len(flat), 24):
        emit("    " + ", ".join(map(str, flat[i : i + 24])) + ",")
    emit("];")
    emit()
    for name, count in dicts:
        entries.append((name, size, count, ident))

emit(f"pub static ARUCO: [Aruco; {len(entries)}] = [")
for name, size, count, ident in entries:
    emit(f'    Aruco {{ name: "{name}", size: {size}, count: {count}, bytes: &{ident} }},')
emit("];")
emit()

emit("/// An AprilTag family. The tag is a `total` x `total` picture: black, with a one-cell white ring")
emit("/// (`width_at_border` cells wide, plus 2 unless `reversed`) and white where a bit of the code is set.")
emit("/// `bits[i]` is where the i-th most significant bit of a code goes, from the picture's corner.")
emit("pub struct April {")
emit("    pub name: &'static str,")
emit("    pub nbits: usize,")
emit("    pub width_at_border: i32,")
emit("    pub total: i32,")
emit("    pub reversed: bool,")
emit("    pub codes: &'static [u64],")
emit("    pub bits: &'static [(i8, i8)],")
emit("}")
emit()

families = [("16h5", "tag16h5"), ("25h9", "tag25h9"), ("36h11", "tag36h11"), ("standard_41h12", "tagStandard41h12")]
for name, stem in families:
    c = (src / f"{stem}.c").read_text()
    ident = "APRIL_" + name.upper()
    codes = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)", array_body(c, "codedata"))]
    ncodes = int(re.search(r"ncodes = (\d+)", c).group(1))
    nbits = int(re.search(r"nbits = (\d+)", c).group(1))
    assert len(codes) == ncodes, (stem, len(codes), ncodes)
    bx = {int(i): int(v) for i, v in re.findall(r"bit_x\[(\d+)\] = (-?\d+)", c)}
    by = {int(i): int(v) for i, v in re.findall(r"bit_y\[(\d+)\] = (-?\d+)", c)}
    assert sorted(bx) == list(range(nbits)) and sorted(by) == list(range(nbits)), stem
    width = int(re.search(r"width_at_border = (\d+)", c).group(1))
    total = int(re.search(r"total_width = (\d+)", c).group(1))
    reversed_border = re.search(r"reversed_border = (\w+)", c).group(1) == "true"
    emit(f"static {ident}_CODES: [u64; {ncodes}] = [")
    for i in range(0, ncodes, 4):
        emit("    " + ", ".join(f"0x{v:x}" for v in codes[i : i + 4]) + ",")
    emit("];")
    emit(f"static {ident}_BITS: [(i8, i8); {nbits}] = [")
    emit("    " + ", ".join(f"({bx[i]}, {by[i]})" for i in range(nbits)) + ",")
    emit("];")
    emit()

emit(f"pub static APRIL: [April; {len(families)}] = [")
for name, stem in families:
    c = (src / f"{stem}.c").read_text()
    ident = "APRIL_" + name.upper()
    nbits = int(re.search(r"nbits = (\d+)", c).group(1))
    width = int(re.search(r"width_at_border = (\d+)", c).group(1))
    total = int(re.search(r"total_width = (\d+)", c).group(1))
    rev = re.search(r"reversed_border = (\w+)", c).group(1)
    emit(
        f'    April {{ name: "{name}", nbits: {nbits}, width_at_border: {width}, total: {total}, '
        f"reversed: {rev}, codes: &{ident}_CODES, bits: &{ident}_BITS }},"
    )
emit("];")

Path(__file__).resolve().parent.parent.joinpath("code-maker-src/src/tags.rs").write_text("\n".join(out) + "\n")
